def region_name(value):
    if not isinstance(value,str):return value
    return REGION_NAMES.get(value.strip(),value.strip())

def region_terms(value):
    name=region_name(value)
    return ' '.join(alias for alias,target in REGION_NAMES.items() if target==name) if name in REGION_ORDER else str(value or '')

def region_options(values):
    names={region_name(value) for value in values if value}
    return [name for name in REGION_ORDER if name in names]+sorted(names-set(REGION_ORDER))
